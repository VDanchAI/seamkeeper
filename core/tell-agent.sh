#!/bin/bash
#
# ═══ ЧТО ЭТО ═══════════════════════════════════════════════════════════════
# Запасной канал ВВОДА: сказать агенту канала из ДРУГОГО терминала, когда
# Telegram лежит.
#
# ═══ ЗАЧЕМ ═════════════════════════════════════════════════════════════════
# Правило владельца 14.08.2026 + мультимодельное ревью. Когда основной путь
# (Telegram) недоступен, нужен способ передать агенту команду, не заходя
# внутрь его tmux-pane.
#
# ═══ КАК РАБОТАЕТ ══════════════════════════════════════════════════════════
# ПОЧЕМУ НЕ attach: канал запущен `exec claude` — claude единственный процесс
# pane. Ctrl-C/Ctrl-D в attached pane УБЬЁТ канал; attach ресайзит pane
# (SIGWINCH) и мусорит TUI. Поэтому ввод — только через send-keys из отдельной
# сессии, НЕ заходя в pane.
#
# ПОЧЕМУ `-l` (literal) ОБЯЗАТЕЛЕН: без него send-keys трактует токены как
# КЛАВИШИ — `Enter`, `C-c`, `;` в тексте станут нажатиями. С `-l` весь текст
# идёт как есть. Перевод строки внутри `-l` = преждевременная отправка (TUI
# примет \n как Enter), поэтому \n схлопываем в пробел, а Enter шлём ОДИН раз
# отдельно.
#
# Префикс [TERM] — соглашение: «это из терминала, отвечай ЗДЕСЬ (в pane),
# reply НЕ вызывай» (иначе агент по привычке ответит в Telegram, куда
# владелец в аварии не смотрит).
#
# Использование (из SSH-сессии, НЕ внутри tmux attach):
#   bash ~/core/tell-agent.sh "твой вопрос агенту"
#   tmux capture-pane -t telegram -p -S -40      # посмотреть ответ агента в pane
# ═══════════════════════════════════════════════════════════════════════════

set -uo pipefail
SESSION="${CHANNEL_TMUX_SESSION:-telegram}"

MSG="$*"
if [ -z "${MSG// /}" ]; then
    echo "Usage: tell-agent.sh <текст сообщения агенту>" >&2
    exit 1
fi

if ! TMUX= tmux has-session -t "$SESSION" 2>/dev/null; then
    echo "ОШИБКА: сессия '$SESSION' не найдена. Канал лежит целиком — сначала подними:" >&2
    echo "  bash ~/core/channel-resurrect.sh   (или start-claude-telegram.sh)" >&2
    exit 1
fi

# схлопываем переводы строк, чтобы TUI не отправил обрезок раньше времени
FLAT=$(printf '%s' "$MSG" | tr '\n' ' ')

# literal-ввод + отдельный Enter; TMUX= — чтобы работать и будучи вызванным из другого tmux
TMUX= tmux send-keys -t "$SESSION" -l "[TERM] $FLAT"
sleep 0.5
TMUX= tmux send-keys -t "$SESSION" Enter

echo "→ отправлено в сессию '$SESSION'. Ответ смотри: tmux capture-pane -t $SESSION -p -S -40"
