#!/bin/bash
#
# ═══ ЧТО ЭТО ═══════════════════════════════════════════════════════════════
# Heartbeat канала Telegram ↔ Claude Code: три отметки-таймстампа — «сообщение
# принято», «ответ выдан», «идёт работа» — для детектора тихих отказов.
#
# ═══ ЗАЧЕМ ═════════════════════════════════════════════════════════════════
# Watchdog умеет проверять только живость процессов. Он не видит отказ, при
# котором всё «живое», а сообщение остаётся без ответа — именно так 30.07
# сообщение владельца пролежало 1.5 суток (кончилась подписка: поллер
# забирал, сессия ответить не могла).
#
# ═══ КАК РАБОТАЕТ ══════════════════════════════════════════════════════════
# Сессия сама отмечает моменты — когда СООБЩЕНИЕ ПРИНЯТО и когда ОТВЕТ ВЫДАН.
# Их сопоставление точно отличает здоровый простой от обрыва, не зная природы
# отказа:
#   принято <= отвечено          → тишина, всё в порядке (владелец просто не пишет)
#   принято >  отвечено + grace  → приняли и не ответили = тихий отказ
#
# Третья отметка `activity` (PostToolUse) снимает ложные тревоги на длинных
# задачах: одна сессия думала ~10 минут над сложным вопросом, и всё это время
# «принято» законно висело новее «отвеченного». Без неё watchdog вопил бы на
# каждой долгой работе, владелец перестал бы читать тревоги — а тревога,
# которую перестают читать, хуже её отсутствия. Правило:
#   принято > отвечено, activity свежая  → идёт работа, молчим
#   принято > отвечено, activity протухла → вот теперь действительно завис
#
# Вызывается хуками Claude Code: UserPromptSubmit → prompt, Stop → stop,
# PostToolUse → activity. Намеренно тупой и быстрый: хук в горячем пути
# каждого сообщения, ошибка здесь не должна ломать разговор — поэтому
# всегда exit 0.
# ═══════════════════════════════════════════════════════════════════════════

# Эти хуки живут в ~/.claude/settings.json, поэтому срабатывают в ЛЮБОЙ сессии
# Claude Code на машине — включая посторонние автономные агенты, которые тоже
# отвечают владельцу через свой собственный процесс. Их отметка выглядела бы
# как «канал жив», и детектор тихого отказа выше перестал бы отличать
# работающий канал от мёртвого: бот-то отвечает, а канал нет. Такой сторонний
# процесс обязан помечать свои подпроцессы отдельной env-переменной и выходить
# из этого хука раньше — см. пример ниже. Имя переменной ниже — просто пример
# (сервис-компаньон одного из авторов назывался так); если у тебя другой
# сторонний бэкенд, используй своё имя переменной и export её в его окружении.
[ -n "$JARVIS_BACKEND" ] && exit 0

# W2 находка: одной проверки выше мало. Хуки в ~/.claude/settings.json бьют
# в ЛЮБОЙ claude-сессии машины (ручные, аудиты, фоновая память) — все они
# писали бы last_prompt/activity/stop, и детектор тихого отказа терял смысл:
# чужой prompt без Stop душил бы здоровый канал, чужая activity прятала бы
# настоящий отказ. Поэтому сигнал пишет ТОЛЬКО канальная сессия. Два
# независимых пути (как у cli-digest):
#   env CHANNEL_SESSION=1  — чистый, вписывается в start-скрипт канала;
#   tmux-имя == telegram   — работает для УЖЕ живой сессии без рестарта.
# Проверено живьём: из дочернего bash `tmux display-message -p '#S'` = `telegram`.
# РИСК: канал вне tmux (гипотетически systemd) → не запишет → сторож сочтёт мёртвым.
# Митигация: env CHANNEL_SESSION=1 в start-скрипте. Откат: убрать блок → как было.
# ФИКС (DEMONSTRATED): без гарда `-n "$TMUX"` вызов `tmux display-message` из
# процесса БЕЗ своего tmux подключается к дефолтному сокету и возвращает имя
# ПОСЛЕДНЕЙ сессии (`telegram`) — тогда headless claude (фоновые задачи, `claude -p`)
# ложно проходил бы фильтр и снова писал last_*. Канал ВСЕГДА имеет $TMUX
# (стартует через tmux new-session), поэтому гард отсекает именно tmux-less чужаков.
CHANNEL_TMUX="${CHANNEL_TMUX_SESSION:-telegram}"
if [ "${CHANNEL_SESSION:-0}" != "1" ]; then
    [ -n "$TMUX" ] || exit 0
    _tn=$(tmux display-message -p '#S' 2>/dev/null)
    [ "$_tn" = "$CHANNEL_TMUX" ] || exit 0
fi

STATE_DIR="${CHANNEL_STATE_DIR:-$HOME/.local/state/claude-telegram}"
KIND="${1:-unknown}"

case "$KIND" in
    prompt|stop|activity) ;;
    *) exit 0 ;;   # неизвестный вид — молча выходим, не мешаем сессии
esac

mkdir -p "$STATE_DIR" 2>/dev/null || exit 0
printf '%s\n' "$(date +%s)" > "$STATE_DIR/last_$KIND" 2>/dev/null

exit 0
